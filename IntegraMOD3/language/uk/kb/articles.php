[anchor=push][b]Увімкнути push-сповіщення[/b][/anchor]

Піктограма сповіщення не вмикає. Це лише вікно того самого браузера, яким ви її додавали. Push належить цьому браузеру й починає працювати лише після дозволу, коли ви вже увійшли.

Відкрийте форум з нової піктограми, не зі старої вкладки. Увійдіть там. Далі в профілі: [b]Панель керування[/b] → [b]Налаштування форуму[/b] → [b]Push-сповіщення[/b].

Ця сторінка підписує [i]цей[/i] браузер або вікно додатка. Натисніть [b]Увімкнути сповіщення браузера[/b]. Браузер запитає дозвіл; оберіть [b]Дозволити[/b]. Якщо все вийшло, на сторінці буде [b]Цей браузер підписаний.[/b]

Сам дозвіл лише дає форуму право надсилати. Нижче позначте [b]Web Push[/b] для подій, які вам потрібні (приватні повідомлення, вподобання, підписані теми тощо), і натисніть [b]Відіслати[/b].

Повторіть це на кожному телефоні, планшеті чи комп’ютері, куди ви встановили форум. Увімкнення на одному пристрої не вмикає його на інших. Якщо [b]Увімкнути сповіщення браузера[/b] нічого не робить, браузер або розширення блокує сповіщення для цього сайту. Дозвольте їх для форуму й натисніть кнопку ще раз.

[b]Ще кілька зауваг[/b]
[list]
[*]Один раз відкрийте нову піктограму й увійдіть. Вхід залишається в тому браузері, яким ви її додавали.
[*]Якщо піктограма відкриває порожню сторінку, видаліть її й додайте знову з поточної HTTPS-адреси, а не зі старої закладки.
[*]Оновлення форуму не змушує створювати піктограму знову.
[/list]

