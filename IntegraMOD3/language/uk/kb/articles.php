[anchor=run][b]Запустити установник[/b][/anchor]

Відкрийте [b]https://ваш-сайт/forum/install/[/b] (додайте [b]install/[/b] до місця, куди завантажили файли).

[list=1]
[*]Прочитайте вступ і відкрийте вкладку [b]INSTALL[/b].
[*]Сторінка вимог перевіряє PHP і теки. Виправте все обов’язкове, перш ніж продовжувати.
[*]Введіть тип бази, ім’я хоста, назву, користувача й пароль. Порт залиште порожнім, якщо хостер не дав окремий. Залиште префікс таблиць, якщо в тій самій базі вже немає іншого форуму.
[*]Оберіть тип кешу (вище).
[*]Створіть перший обліковий запис адміністратора (ваш логін).
[*]Дозвольте записати [b]config.php[/b]. Якщо не вийде, він покаже вміст, щоб вставити вручну.
[/list]

Коли з’явиться вітання, форум установлено.

