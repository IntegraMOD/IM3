[anchor=banner][b]Створити зображення банера[/b][/anchor]

Створіть зображення банера розміром не більше [b]200px завширшки та 50px заввишки[/b]. Приймаються типи файлів [b]JPG[/b], [b]JPEG[/b], [b]GIF[/b] і [b]PNG[/b].

