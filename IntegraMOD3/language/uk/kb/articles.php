[anchor=lang][b]Перекласти статтю[/b][/anchor]

Можна тримати одну статтю в Базі знань і все одно показувати інший заголовок, опис і текст для кожної мови форуму.

[b]1. Оберіть коротке ім’я[/b]

Великі літери та підкреслення. Приклад: [b]PUSH_NOTIFICATIONS[/b].

Читачі цього імені не бачать. Воно лише зв’язує статтю з перекладами.

[b]2. У формі статті поставте лише заповнювач[/b]

Кожне поле має бути заповнювачем і нічим іншим. Не змішуйте його з іншим текстом.

[list]
[*]Заголовок: [b]{L_PUSH_NOTIFICATIONS}[/b]
[*]Опис: [b]{L_PUSH_NOTIFICATIONS_DESC}[/b]
[*]Текст статті: [b]{L_PUSH_NOTIFICATIONS_ARTICLE}[/b]
[/list]

[b]3. Справжній текст запишіть у мовні файли[/b]

Відкрийте [b]language/en/kb/articles.php[/b] і додайте три рядки:

[code]PUSH_NOTIFICATIONS         => Push notifications
PUSH_NOTIFICATIONS_DESC    => Turn on browser alerts.
PUSH_NOTIFICATIONS_ARTICLE => The full article text goes here.[/code]

Скопіюйте ті самі три імена в [b]language/nl/kb/articles.php[/b], [b]language/de/kb/articles.php[/b] і кожну іншу мовну теку, яку використовуєте, з перекладеним текстом.

Англійська обов’язкова. Якщо в мові немає рядка, показується англійський текст.

[b]4. Як зберегти файл[/b]

Збережіть як UTF-8 без BOM. Notepad++ це вміє. Блокнот Windows часто ні, і це може зламати форум.

Ось і все. Після очищення кешу кожен читач бачить статтю своєю мовою.

