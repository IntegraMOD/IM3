[anchor=after][b]Після цього — видалити ці теки[/b][/anchor]

Ці шляхи не повинні бути на публічному сайті. Видаліть їх із вебкореня (або зніміть із сервера). Залишати їх — дірка в безпеці.

[list]
[*][b]install/[/b] — [b]обов’язково[/b] прибрати. Поки тека є, працює лише Панель адміністратора, і той, хто її відкриє, може зламати форум.
[*][b]develop/[/b] — [b]цю видаліть особливо.[/b] Інструменти розробки й тестовий код. Ніколи не лишайте на живому форумі.
[*][b]stk/[/b] — Support Toolkit. Корисний, коли ремонтуєте зламаний форум; небезпечний, якщо чужі можуть його відкрити. Приберіть, коли закінчите.
[*][b]docs/[/b] — нотатки встановлення. Можна видалити після прочитання.
[/list]

За бажанням: конвертуйте старий форум phpBB 2 з посилання конвертера на сторінці успіху [i]перед[/i] видаленням [b]install/[/b].

Потім увійдіть обліковим записом адміністратора, який створили.

