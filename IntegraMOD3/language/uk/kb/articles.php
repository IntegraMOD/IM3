Приклад: для [b]https://integramod.com/forum/[/b] назвіть зображення [b]integramod.com+forum.jpg[/b]. Можна використати те саме ім’я з іншим дозволеним розширенням, наприклад [b]integramod.com+forum.jpeg[/b], [b]integramod.com+forum.gif[/b] або [b]integramod.com+forum.png[/b].

Коли блок Site Banner Exchange показує схвалений банер, він відновлює URL з імені файлу, замінюючи [b]+[/b] на [b]/[/b].

