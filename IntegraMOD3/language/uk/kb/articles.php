[anchor=approve][b]Потрібне схвалення[/b][/anchor]

Усі подання Banner Exchange потребують схвалення адміністратора або модератора, перш ніж подання буде завершене. Повідомлення потрібно схвалити через звичайну чергу модерації.

Коли адміністратор або модератор схвалює повідомлення, підготовлений банер переміщується з [b]images/links/tmp/[/b] до [b]images/links/[/b]. Запис черги позначається як схвалений із зазначенням того, хто схвалив, і часу схвалення.

До цього схвалення банер лише очікує. Його не слід вважати активним банером Site Banner Exchange.

