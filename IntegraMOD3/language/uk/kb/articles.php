[anchor=cache][b]Вибір кешу[/b][/anchor]

Установник запитує, де зберігати кешовані дані. Оберіть те, що хостер справді має.

[list]
[*][b]File (типово)[/b] — пише файли кешу в [b]store/[/b]. Просто й надійно. Беріть на більшості спільного хостингу.
[*][b]Memcache[/b] або [b]Memcached[/b] — швидкий кеш у пам’яті. Потрібне розширення PHP і сервер memcached.
[*][b]Redis[/b] — швидке сховище в пам’яті з додатковими можливостями. Потрібне розширення Redis і сервер Redis.
[*][b]APC / APCu[/b] — кеш у пам’яті всередині PHP на одному сервері.
[*][b]WinCache[/b] — лише хости Windows.
[*][b]XCache[/b] / [b]eAccelerator[/b] — старіші opcode-кеші; лише якщо хостер їх ще має.
[*][b]Memory (лише процес)[/b] — швидко, але кожен процес PHP має свій кеш. Не спільно.
[*][b]Без кешу[/b] — лише для налагодження. Не на живому форумі.
[/list]

Якщо не впевнені, залиште [b]File[/b]. Пізніше можна змінити в ACP, якщо хостер додасть Memcached або Redis.

