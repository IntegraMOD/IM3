[anchor=config][b]Захистити config.php[/b][/anchor]

[b]config.php[/b] містить пароль бази. Під час установлення його часто ставлять у [b]666[/b] (доступний для запису всім), щоб установник міг писати. Так залишати не можна.

Після встановлення:

[list]
[*]Поставте [b]config.php[/b] на [b]644[/b] (або [b]640[/b], якщо хостер дозволяє). Вебсервер усе одно має [i]читати[/i] його.
[*]Не лишайте [b]666[/b]. Хто може писати цей файл, той володіє базою.
[/list]

